/**
 * Product Image Generator Script
 * Scans all product folders and generates productImages.ts automatically
 * Run with: node scripts/generate-product-images.js
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

const IMAGES_DIR = path.join(__dirname, '..', 'public', 'images');
const OUTPUT_FILE = path.join(__dirname, '..', 'src', 'lib', 'productImages.ts');

/**
 * Auto-discover all product folders in the images directory
 */
function discoverProductFolders() {
  try {
    if (!fs.existsSync(IMAGES_DIR)) {
      console.warn(`⚠️  Images directory not found: ${IMAGES_DIR}`);
      return {};
    }
    
    const entries = fs.readdirSync(IMAGES_DIR, { withFileTypes: true });
    const folders = {};
    
    entries.forEach(entry => {
      if (entry.isDirectory() && entry.name.includes('-page')) {
        // Use folder name as both key and value for consistency
        folders[entry.name] = entry.name;
      }
    });
    
    return folders;
  } catch (error) {
    console.error(`Error discovering folders: ${error.message}`);
    return {};
  }
}

/**
 * Get all image files from a directory
 */
function getImageFiles(dirPath) {
  try {
    if (!fs.existsSync(dirPath)) {
      console.warn(`⚠️  Directory not found: ${dirPath}`);
      return [];
    }
    
    const files = fs.readdirSync(dirPath);
    const imageExtensions = ['.jpg', '.jpeg', '.png', '.webp', '.gif'];
    
    return files
      .filter(file => {
        const ext = path.extname(file).toLowerCase();
        return imageExtensions.includes(ext);
      })
      .sort(); // Sort alphabetically for consistency
  } catch (error) {
    console.error(`Error reading directory ${dirPath}:`, error.message);
    return [];
  }
}

/**
 * Generate the productImages.ts file content
 */
function generateProductImagesFile() {
  // Auto-discover product folders
  const PRODUCT_FOLDERS = discoverProductFolders();
  
  if (Object.keys(PRODUCT_FOLDERS).length === 0) {
    console.warn('⚠️  No product folders found!');
    return null;
  }
  
  console.log(`📁 Found ${Object.keys(PRODUCT_FOLDERS).length} product folders\n`);
  console.log('🔍 Scanning product folders...\n');
  
  const productImages = {};
  let totalImages = 0;
  
  // Scan each product folder
  for (const [key, folderName] of Object.entries(PRODUCT_FOLDERS)) {
    const folderPath = path.join(IMAGES_DIR, folderName);
    const imageFiles = getImageFiles(folderPath);
    
    if (imageFiles.length === 0) {
      console.warn(`⚠️  No images found in: ${folderName}`);
    } else {
      console.log(`✅ ${folderName}: Found ${imageFiles.length} images`);
      totalImages += imageFiles.length;
    }
    
    // Create image paths - always encode filenames for web compatibility
    productImages[key] = imageFiles.map(fileName => {
      // Always encode the filename to handle spaces and special characters
      // This ensures URLs work correctly in browsers
      const encodedFileName = encodeURIComponent(fileName);
      return `    '/images/${folderName}/${encodedFileName}',`;
    });
  }
  
  console.log(`\n📊 Total images found: ${totalImages}\n`);
  
  // Generate the TypeScript file content
  const fileContent = `/**
 * Product Image Lists
 * AUTO-GENERATED FILE - Do not edit manually!
 * Generated by: scripts/generate-product-images.js
 * Last generated: ${new Date().toISOString()}
 * 
 * Maps product folder names to their available images
 * This ensures reliable image loading for product detail pages
 * ALL images from each folder are automatically included here
 */

export const PRODUCT_IMAGES: Record<string, string[]> = {
${Object.entries(productImages).map(([key, paths]) => {
  if (paths.length === 0) {
    return `  '${key}': [],`;
  }
  return `  '${key}': [\n${paths.join('\n')}\n  ],`;
}).join('\n\n')}
};

/**
 * Get images for a product folder
 */
export function getProductImages(folderName: string): string[] {
  return PRODUCT_IMAGES[folderName] || [];
}
`;

  return fileContent;
}

/**
 * Main execution
 */
function main() {
  console.log('🚀 Starting Product Image Generator...\n');
  
  // Check if images directory exists
  if (!fs.existsSync(IMAGES_DIR)) {
    console.error(`❌ Images directory not found: ${IMAGES_DIR}`);
    process.exit(1);
  }
  
  // Generate the file content
  const content = generateProductImagesFile();
  
  if (!content) {
    console.error('❌ Failed to generate content');
    process.exit(1);
  }
  
  // Write to file
  try {
    fs.writeFileSync(OUTPUT_FILE, content, 'utf8');
    console.log(`✅ Successfully generated: ${OUTPUT_FILE}`);
    console.log('✨ All product images have been automatically loaded!\n');
  } catch (error) {
    console.error(`❌ Error writing file: ${error.message}`);
    process.exit(1);
  }
}

// Run the script
main();

